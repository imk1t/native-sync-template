#!/usr/bin/env python3
"""shared/tokens から SwiftUI / Compose の定数を生成する。出力は決定的（再生成して差分が出ないこと）。"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
tokens = json.loads((ROOT / "shared/tokens/tokens.json").read_text(encoding="utf-8"))


def flat(group):
    return [(k, v["$value"]) for k, v in sorted(tokens[group].items())]


def cap(s):
    return s[0].upper() + s[1:]


def swift():
    out = ["// Generated by tools/generate.py. Do not edit.", "import SwiftUI", "", "public enum Tokens {", "    public enum Color {"]
    for k, v in flat("color"):
        out.append(f"        public static let {k} = SwiftUI.Color(hex: 0x{v.lstrip('#')[:6]})")
    out += ["    }", "    public enum Spacing {"]
    for k, v in flat("spacing"):
        out.append(f"        public static let {k}: CGFloat = {v}")
    out += ["    }", "}", "",
            "extension SwiftUI.Color {",
            "    init(hex: UInt32) {",
            "        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255)",
            "    }", "}", ""]
    return "\n".join(out)


def kotlin():
    out = ["// Generated by tools/generate.py. Do not edit.", "package com.example.designsystem", "",
           "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.unit.dp", "", "object Tokens {", "    object Colors {"]
    for k, v in flat("color"):
        out.append(f"        val {k} = Color(0xFF{v.lstrip('#')[:6].upper()})")
    out += ["    }", "    object Spacing {"]
    for k, v in flat("spacing"):
        out.append(f"        val {k} = {v}.dp")
    out += ["    }", "}", ""]
    return "\n".join(out)


def write(path, text):
    p = ROOT / path
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


write("modules/designsystem/ios/Sources/DesignSystem/Generated/Tokens.swift", swift())
write("modules/designsystem/android/src/main/kotlin/com/example/designsystem/generated/Tokens.kt", kotlin())
print("generated")
