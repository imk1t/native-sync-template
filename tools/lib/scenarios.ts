/**
 * specs/scenarios の given にある API レスポンスを、両 OS のテスト用コードとして生成する。
 *
 * - 出力先はシナリオの feature のテストディレクトリ（iOS は Generated/、Android は generated/）
 * - `ScenarioFixtures.<シナリオ>.<step>` の名前は両 OS で同じ。tools/check-scenarios.ts がテストからの参照を検査する
 * - operationId の値は 1 件、または返す順に並べた配列。配列の最後のレスポンスは、以降の同じリクエストにも返す
 * - API を使わない given（localState・navigation・localization）は生成しない
 */
import { rmSync } from "node:fs";
import { basename } from "node:path";
import type { Operation, Spec } from "./openapi";
import { type Dict, glob, isDict, join, readText, readYaml } from "./util";

const SWIFT_FILE = "ScenarioFixtures.swift";
const KOTLIN_FILE = "ScenarioFixtures.kt";
/** 生成物の場所（git の glob pathspec）。tools/check-generated.ts が差分の検査に使う。 */
export const PATHSPECS = [`:(glob)modules/**/Generated/${SWIFT_FILE}`, `:(glob)modules/**/generated/${KOTLIN_FILE}`];

export type Stub = {
  operation: string;
  method: string;
  path: string;
  status: number;
  headers: [string, string][];
  body: string;
  pending: boolean;
};
export type Step = { id: string; member: string; stubs: Stub[] };
export type Scenario = { name: string; type: string; feature: string; steps: Step[] };

/** `load-succeeds` → `loadSucceeds`。 */
export function memberName(id: string): string {
  const [head = "", ...rest] = id.split("-");
  const name = head + rest.map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");
  if (!/^[a-z][A-Za-z0-9]*$/.test(name)) throw new Error(`step id を識別子にできません: ${id}`);
  return name;
}

/** `github-search` → `GithubSearch`。 */
export function typeName(name: string): string {
  const member = memberName(name);
  return member.charAt(0).toUpperCase() + member.slice(1);
}

function stub(op: Operation, raw: unknown): Stub {
  const base = { operation: op.id, method: op.method, path: op.path };
  if (!isDict(raw)) throw new Error(`${op.id}: レスポンスを辞書で書いてください`);
  if (raw.pending === true) return { ...base, status: 0, headers: [], body: "", pending: true };
  const headers = isDict(raw.headers)
    ? Object.entries(raw.headers).map(([k, v]) => [k, String(v)] as [string, string])
    : [];
  const body = "body" in raw ? JSON.stringify(raw.body) : "";
  return { ...base, status: Number(raw.status), headers, body, pending: false };
}

/** API レスポンスを 1 件以上持つシナリオを返す。形式の検査は tools/check-scenarios.ts が行う。 */
export function load(root: string, spec: Spec): Scenario[] {
  const ops = new Map(spec.operations.map((op) => [op.id, op]));
  const dir = join(root, "specs/scenarios");
  const scenarios: Scenario[] = [];
  for (const file of glob(dir, "*.yaml")) {
    const doc = readYaml(join(dir, file));
    if (!isDict(doc) || typeof doc.feature !== "string" || !Array.isArray(doc.steps)) continue;
    const name = basename(file, ".yaml");
    const steps: Step[] = [];
    for (const step of doc.steps as unknown[]) {
      if (!isDict(step) || typeof step.id !== "string" || !isDict(step.given)) continue;
      const stubs: Stub[] = [];
      for (const [key, value] of Object.entries(step.given as Dict)) {
        const op = ops.get(key);
        if (!op) continue;
        for (const raw of Array.isArray(value) ? value : [value]) stubs.push(stub(op, raw));
      }
      if (stubs.length > 0) steps.push({ id: step.id, member: memberName(step.id), stubs });
    }
    if (steps.length > 0) scenarios.push({ name, type: typeName(name), feature: doc.feature, steps });
  }
  return scenarios;
}

/** テストがレスポンスとして使う step か（保留だけの step は各テストが自分で待たせる）。 */
export function servesResponses(step: Step): boolean {
  return step.stubs.some((s) => !s.pending);
}

/** Swift と Kotlin で同じ意味になる文字列リテラル。 */
function literal(text: string, kotlin: boolean): string {
  let out = "";
  for (const ch of text) {
    const code = ch.codePointAt(0) as number;
    if (ch === "\\") out += "\\\\";
    else if (ch === '"') out += '\\"';
    else if (ch === "\n") out += "\\n";
    else if (ch === "\r") out += "\\r";
    else if (ch === "\t") out += "\\t";
    else if (ch === "$" && kotlin) out += "\\$";
    else if (code < 0x20 || code === 0x7f) {
      const hex = code.toString(16).padStart(4, "0");
      out += kotlin ? `\\u${hex}` : `\\u{${hex}}`;
    } else out += ch;
  }
  return `"${out}"`;
}

const HEADER = "// Generated by tools/generate.ts from specs/scenarios. Do not edit.";

export function swift(scenarios: Scenario[]): string {
  const out = [
    HEADER,
    "import CoreNetwork",
    "import Foundation",
    "",
    "/// シナリオの given にある API レスポンス 1 件。",
    "struct ScenarioStub: Sendable {",
    "    let operation: String",
    "    let method: String",
    "    let path: String",
    "    let status: Int",
    "    let headers: [String: String]",
    "    let body: String",
    "    /// true のときはレスポンスを返さず、テストが待たせる。",
    "    let pending: Bool",
    "",
    "    /// path の `{name}` は任意の 1 セグメントに一致する。",
    "    func matches(method: String, path: String) -> Bool {",
    '        let expected = self.path.split(separator: "/", omittingEmptySubsequences: false)',
    '        let actual = path.split(separator: "/", omittingEmptySubsequences: false)',
    "        guard method == self.method, expected.count == actual.count else { return false }",
    '        return zip(expected, actual).allSatisfy { $0.hasPrefix("{") || $0 == $1 }',
    "    }",
    "}",
    "",
    "/// シナリオの 1 step。stubs は given に書いた順。",
    "struct ScenarioStep: Sendable {",
    "    let id: String",
    "    let stubs: [ScenarioStub]",
    "}",
    "",
    "/// step の given どおりにレスポンスを返す Transport。同じ operationId の複数のレスポンスは、リクエストのたびに順に返し、",
    "/// 最後のレスポンスは以降も返す。given に無いリクエストには 404 を返す。送ったリクエストは requests に残る。",
    "actor ScenarioTransport: HTTPTransport {",
    "    private let stubs: [ScenarioStub]",
    "    private var counts: [String: Int] = [:]",
    "    private(set) var requests: [HTTPRequest] = []",
    "",
    "    init(_ step: ScenarioStep) { stubs = step.stubs.filter { !$0.pending } }",
    "",
    "    func send(_ request: HTTPRequest) async throws -> HTTPResponse {",
    "        requests.append(request)",
    "        let matching = stubs.filter { $0.matches(method: request.method, path: request.path) }",
    "        guard let operation = matching.first?.operation else { return HTTPResponse(status: 404) }",
    "        let candidates = matching.filter { $0.operation == operation }",
    "        let index = counts[operation, default: 0]",
    "        counts[operation] = index + 1",
    "        let stub = candidates[min(index, candidates.count - 1)]",
    "        return HTTPResponse(status: stub.status, body: Data(stub.body.utf8), headers: stub.headers)",
    "    }",
    "}",
    "",
    "enum ScenarioFixtures {",
  ];
  for (const scenario of scenarios) {
    out.push(`    enum ${scenario.type} {`);
    for (const step of scenario.steps) {
      out.push(
        `        static let ${step.member} = ScenarioStep(`,
        `            id: ${literal(`${scenario.name}/${step.id}`, false)},`,
        "            stubs: [",
      );
      for (const s of step.stubs) {
        const headers =
          s.headers.length === 0
            ? "[:]"
            : `[${s.headers.map(([k, v]) => `${literal(k, false)}: ${literal(v, false)}`).join(", ")}]`;
        out.push(
          "                ScenarioStub(",
          `                    operation: ${literal(s.operation, false)}, method: ${literal(s.method, false)}, path: ${literal(s.path, false)},`,
          `                    status: ${s.status}, headers: ${headers},`,
          `                    body: ${literal(s.body, false)},`,
          `                    pending: ${s.pending}),`,
        );
      }
      out.push("            ])");
    }
    out.push("    }");
  }
  out.push("}", "");
  return out.join("\n");
}

export function kotlin(scenarios: Scenario[], pkg: string): string {
  const out = [
    HEADER,
    `package ${pkg}`,
    "",
    "import com.example.core.network.HttpRequest",
    "import com.example.core.network.HttpResponse",
    "import com.example.core.network.HttpTransport",
    "",
    "/** シナリオの given にある API レスポンス 1 件。pending が true のときはレスポンスを返さず、テストが待たせる。 */",
    "internal class ScenarioStub(",
    "    val operation: String,",
    "    val method: String,",
    "    val path: String,",
    "    val status: Int,",
    "    val headers: Map<String, String>,",
    "    val body: String,",
    "    val pending: Boolean",
    ") {",
    "    /** path の `{name}` は任意の 1 セグメントに一致する。 */",
    "    fun matches(method: String, path: String): Boolean {",
    '        val expected = this.path.split("/")',
    '        val actual = path.split("/")',
    "        return method == this.method && expected.size == actual.size &&",
    '            expected.zip(actual).all { (e, a) -> e.startsWith("{") || e == a }',
    "    }",
    "}",
    "",
    "/** シナリオの 1 step。stubs は given に書いた順。 */",
    "internal class ScenarioStep(val id: String, val stubs: List<ScenarioStub>)",
    "",
    "/**",
    " * step の given どおりにレスポンスを返す Transport。同じ operationId の複数のレスポンスは、リクエストのたびに順に返し、",
    " * 最後のレスポンスは以降も返す。given に無いリクエストには 404 を返す。送ったリクエストは requests に残る。",
    " */",
    "internal class ScenarioTransport(step: ScenarioStep) : HttpTransport {",
    "    private val stubs = step.stubs.filter { !it.pending }",
    "    private val counts = mutableMapOf<String, Int>()",
    "    val requests = mutableListOf<HttpRequest>()",
    "",
    "    override suspend fun send(request: HttpRequest): HttpResponse {",
    "        requests.add(request)",
    "        val matching = stubs.filter { it.matches(request.method, request.path) }",
    "        val operation = matching.firstOrNull()?.operation ?: return HttpResponse(404)",
    "        val candidates = matching.filter { it.operation == operation }",
    "        val index = counts.getOrDefault(operation, 0)",
    "        counts[operation] = index + 1",
    "        val stub = candidates[minOf(index, candidates.size - 1)]",
    "        return HttpResponse(stub.status, stub.body, stub.headers)",
    "    }",
    "}",
    "",
    "internal object ScenarioFixtures {",
  ];
  for (const scenario of scenarios) {
    out.push(`    object ${scenario.type} {`);
    for (const step of scenario.steps) {
      out.push(
        `        val ${step.member} = ScenarioStep(`,
        `            ${literal(`${scenario.name}/${step.id}`, true)},`,
        "            listOf(",
      );
      step.stubs.forEach((s, index) => {
        const headers =
          s.headers.length === 0
            ? "emptyMap()"
            : `mapOf(${s.headers.map(([k, v]) => `${literal(k, true)} to ${literal(v, true)}`).join(", ")})`;
        out.push(
          "                ScenarioStub(",
          `                    ${literal(s.operation, true)}, ${literal(s.method, true)}, ${literal(s.path, true)},`,
          `                    ${s.status}, ${headers},`,
          `                    ${literal(s.body, true)},`,
          `                    ${s.pending}`,
          `                )${index < step.stubs.length - 1 ? "," : ""}`,
        );
      });
      out.push("            )", "        )");
    }
    out.push("    }");
  }
  out.push("}", "");
  return out.join("\n");
}

/** modules/Package.swift の testTarget から、モジュールの iOS テストディレクトリを返す。 */
function iosTestDir(root: string, feature: string): string {
  const text = readText(join(root, "modules/Package.swift"));
  for (const [, path = ""] of text.matchAll(/^\s*\.testTarget\(.*\bpath:\s*"([^"]+)"/gm)) {
    if (path.startsWith(`${feature}/ios/Tests/`)) return `modules/${path}`;
  }
  throw new Error(`${feature}: modules/Package.swift に iOS の testTarget がありません`);
}

/** `shared/github-rest` → `com.example.shared.githubrest`（AGENTS.md の命名規則）。 */
export function androidPackage(feature: string): string {
  return `com.example.${feature.replaceAll("-", "").split("/").join(".")}`;
}

/** 生成するファイル（リポジトリからの相対パス → 内容）。 */
export function outputs(root: string, spec: Spec): Record<string, string> {
  const byFeature = new Map<string, Scenario[]>();
  for (const scenario of load(root, spec)) {
    byFeature.set(scenario.feature, [...(byFeature.get(scenario.feature) ?? []), scenario]);
  }
  const files: Record<string, string> = {};
  for (const [feature, scenarios] of byFeature) {
    const pkg = androidPackage(feature);
    files[`${iosTestDir(root, feature)}/Generated/${SWIFT_FILE}`] = swift(scenarios);
    files[`modules/${feature}/android/src/test/kotlin/${pkg.split(".").join("/")}/generated/${KOTLIN_FILE}`] = kotlin(
      scenarios,
      pkg,
    );
  }
  return files;
}

/** 以前の生成物を消す（API を使うシナリオが無くなったモジュールに残さない）。 */
export function clean(root: string): void {
  const modules = join(root, "modules");
  for (const pattern of [`**/Generated/${SWIFT_FILE}`, `**/generated/${KOTLIN_FILE}`]) {
    for (const path of glob(modules, pattern)) rmSync(join(modules, path), { force: true });
  }
}
