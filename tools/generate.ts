/**
 * shared/ の定義から Swift / Kotlin のコードを生成する。出力は決定的（再生成して差分が出ないこと）。
 *
 * - shared/tokens/tokens.json → designsystem の Tokens
 * - shared/openapi/openapi.yaml → core/network の DTO と APIClient（tools/lib/openapi.ts）
 * - shared/routes.yaml → core/navigation の Route と AppTab（tools/lib/routes.ts）
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import * as openapi from "./lib/openapi";
import * as routes from "./lib/routes";
import { compare, type Dict, isDict, join, readText, readYaml, ROOT } from "./lib/util";

const IOS_NETWORK = "modules/core/network/ios/Sources/CoreNetwork/Generated";
const ANDROID_NETWORK = "modules/core/network/android/src/main/kotlin/com/example/corenetwork/generated";

/** 生成先のファイル。tools/check-generated.ts もこの一覧を使う。 */
export const OUTPUTS = {
  iosTokens: "modules/designsystem/ios/Sources/DesignSystem/Generated/Tokens.swift",
  androidTokens: "modules/designsystem/android/src/main/kotlin/com/example/designsystem/generated/Tokens.kt",
  iosModels: `${IOS_NETWORK}/APIModels.swift`,
  iosClient: `${IOS_NETWORK}/APIClient.swift`,
  androidModels: `${ANDROID_NETWORK}/ApiModels.kt`,
  androidClient: `${ANDROID_NETWORK}/ApiClient.kt`,
  iosRoutes: "modules/core/navigation/ios/Sources/CoreNavigation/Generated/Routes.swift",
  androidRoutes: "modules/core/navigation/android/src/main/kotlin/com/example/corenavigation/generated/Routes.kt",
} as const;

type Tokens = Record<string, Record<string, { $value: string }>>;

function flat(tokens: Tokens, group: string): [string, string][] {
  const entries = Object.entries(tokens[group] ?? {}).map(([k, v]): [string, string] => [k, String(v.$value)]);
  return entries.sort(([a], [b]) => compare(a, b));
}

function hex(value: string): string {
  return value.replace(/^#+/, "").slice(0, 6);
}

function swiftTokens(tokens: Tokens): string {
  const out = [
    "// Generated by tools/generate.ts. Do not edit.",
    "import SwiftUI",
    "",
    "public enum Tokens {",
    "    public enum Color {",
  ];
  for (const [k, v] of flat(tokens, "color")) {
    out.push(`        public static let ${k} = SwiftUI.Color(hex: 0x${hex(v)})`);
  }
  out.push("    }", "    public enum Spacing {");
  for (const [k, v] of flat(tokens, "spacing")) out.push(`        public static let ${k}: CGFloat = ${v}`);
  out.push(
    "    }",
    "}",
    "",
    "extension SwiftUI.Color {",
    "    init(hex: UInt32) {",
    "        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255)",
    "    }",
    "}",
    "",
  );
  return out.join("\n");
}

function kotlinTokens(tokens: Tokens): string {
  const out = [
    "// Generated by tools/generate.ts. Do not edit.",
    "package com.example.designsystem",
    "",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.unit.dp",
    "",
    "object Tokens {",
    "    object Colors {",
  ];
  for (const [k, v] of flat(tokens, "color")) out.push(`        val ${k} = Color(0xFF${hex(v).toUpperCase()})`);
  out.push("    }", "    object Spacing {");
  for (const [k, v] of flat(tokens, "spacing")) out.push(`        val ${k} = ${v}.dp`);
  out.push("    }", "}", "");
  return out.join("\n");
}

function write(root: string, path: string, text: string): void {
  const target = join(root, path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text, "utf-8");
}

export function generate(root: string = ROOT): void {
  const tokens = JSON.parse(readText(join(root, "shared/tokens/tokens.json"))) as Tokens;
  write(root, OUTPUTS.iosTokens, swiftTokens(tokens));
  write(root, OUTPUTS.androidTokens, kotlinTokens(tokens));

  const api = readYaml(join(root, "shared/openapi/openapi.yaml"));
  const spec = new openapi.Spec(isDict(api) ? api : ({} as Dict));
  write(root, OUTPUTS.iosModels, openapi.swiftModels(spec));
  write(root, OUTPUTS.iosClient, openapi.swiftClient(spec));
  write(root, OUTPUTS.androidModels, openapi.kotlinModels(spec, "com.example.corenetwork"));
  write(root, OUTPUTS.androidClient, openapi.kotlinClient(spec, "com.example.corenetwork"));

  const model = routes.load(readYaml(join(root, "shared/routes.yaml")), root);
  write(root, OUTPUTS.iosRoutes, routes.swift(model));
  write(root, OUTPUTS.androidRoutes, routes.kotlin(model, "com.example.corenavigation"));
}

if (import.meta.main) {
  generate();
  console.log("generated");
}
