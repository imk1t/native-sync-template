/**
 * specs/ の定義から Swift / Kotlin のコードを生成する。出力は決定的（再生成して差分が出ないこと）。
 *
 * - DESIGN.md（front matter）→ shared/designsystem の Tokens（tools/lib/design.ts）
 * - specs/openapi/openapi.yaml → core/network の DTO と APIClient（tools/lib/openapi.ts）
 * - specs/routes.yaml → core/navigation の Route と AppTab（tools/lib/routes.ts）
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import * as design from "./lib/design";
import * as localization from "./lib/localization";
import * as openapi from "./lib/openapi";
import * as routes from "./lib/routes";
import { compare, type Dict, isDict, join, readText, readYaml, ROOT } from "./lib/util";

const IOS_NETWORK = "modules/core/network/ios/Sources/Core/Network/Generated";
const ANDROID_NETWORK = "modules/core/network/android/src/main/kotlin/com/example/core/network/generated";

/** 生成先のファイル。tools/check-generated.ts もこの一覧を使う。 */
export const OUTPUTS = {
  iosTokens: "modules/shared/designsystem/ios/Sources/Shared/DesignSystem/Generated/Tokens.swift",
  androidTokens:
    "modules/shared/designsystem/android/src/main/kotlin/com/example/shared/designsystem/generated/Tokens.kt",
  iosModels: `${IOS_NETWORK}/APIModels.swift`,
  iosClient: `${IOS_NETWORK}/APIClient.swift`,
  androidModels: `${ANDROID_NETWORK}/ApiModels.kt`,
  androidClient: `${ANDROID_NETWORK}/ApiClient.kt`,
  iosRoutes: "modules/core/navigation/ios/Sources/Core/Navigation/Generated/Routes.swift",
  androidRoutes: "modules/core/navigation/android/src/main/kotlin/com/example/core/navigation/generated/Routes.kt",
} as const;

function hex(value: string): string {
  return value.replace(/^#+/, "").slice(0, 6);
}

function swiftTokens(tokens: design.Tokens): string {
  const out = [
    "// Generated by tools/generate.ts. Do not edit.",
    "import SwiftUI",
    "",
    "public enum Tokens {",
    "    public enum Color {",
  ];
  for (const [k, light, dark] of tokens.colors) {
    out.push(`        public static let ${k} = SwiftUI.Color(light: 0x${hex(light)}, dark: 0x${hex(dark)})`);
  }
  out.push("    }", "    public enum Radius {");
  for (const [k, v] of tokens.rounded) out.push(`        public static let ${k}: CGFloat = ${v}`);
  out.push("    }", "    public enum Spacing {");
  for (const [k, v] of tokens.spacing) out.push(`        public static let ${k}: CGFloat = ${v}`);
  out.push(
    "    }",
    "}",
    "",
    "extension SwiftUI.Color {",
    "    init(hex: UInt32) {",
    "        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255)",
    "    }",
    "",
    "    /// OS のライト・ダーク設定に追従する色",
    "    init(light: UInt32, dark: UInt32) {",
    "        self.init(uiColor: UIColor { $0.userInterfaceStyle == .dark ? UIColor(Color(hex: dark)) : UIColor(Color(hex: light)) })",
    "    }",
    "}",
    "",
  );
  return out.join("\n");
}

function kotlinTokens(tokens: design.Tokens): string {
  const out = [
    "// Generated by tools/generate.ts. Do not edit.",
    "package com.example.shared.designsystem",
    "",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.unit.dp",
    "",
    "object Tokens {",
    "    object Colors {",
  ];
  for (const [k, light] of tokens.colors) out.push(`        val ${k} = Color(0xFF${hex(light).toUpperCase()})`);
  out.push("    }", "    object DarkColors {");
  for (const [k, , dark] of tokens.colors) out.push(`        val ${k} = Color(0xFF${hex(dark).toUpperCase()})`);
  out.push("    }", "    object Radius {");
  for (const [k, v] of tokens.rounded) out.push(`        val ${k} = ${v}.dp`);
  out.push("    }", "    object Spacing {");
  for (const [k, v] of tokens.spacing) out.push(`        val ${k} = ${v}.dp`);
  out.push("    }", "}", "");
  return out.join("\n");
}

function write(root: string, path: string, text: string): void {
  const target = join(root, path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text, "utf-8");
}

export function generate(root: string = ROOT): void {
  const pending: Record<string, string> = {};
  const localized = localization.outputs(localization.load(root));
  const tokens = design.parse(readText(join(root, "DESIGN.md")));
  pending[OUTPUTS.iosTokens] = swiftTokens(tokens);
  pending[OUTPUTS.androidTokens] = kotlinTokens(tokens);

  const api = readYaml(join(root, "specs/openapi/openapi.yaml"));
  const spec = new openapi.Spec(isDict(api) ? api : ({} as Dict));
  pending[OUTPUTS.iosModels] = openapi.swiftModels(spec);
  pending[OUTPUTS.iosClient] = openapi.swiftClient(spec);
  pending[OUTPUTS.androidModels] = openapi.kotlinModels(spec, "com.example.core.network");
  pending[OUTPUTS.androidClient] = openapi.kotlinClient(spec, "com.example.core.network");

  const model = routes.load(readYaml(join(root, "specs/routes.yaml")), root);
  pending[OUTPUTS.iosRoutes] = routes.swift(model);
  pending[OUTPUTS.androidRoutes] = routes.kotlin(model, "com.example.core.navigation");

  localization.clean(root);
  for (const [path, text] of Object.entries(pending)) write(root, path, text);
  for (const [path, text] of Object.entries(localized)) write(root, path, text);
}

if (import.meta.main) {
  generate();
  console.log("generated");
}
